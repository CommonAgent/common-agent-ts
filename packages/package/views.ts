/**
 * The generated views of Common Agent 12.5: NOT.md, RECORDS.md and SYSTEMS.md
 * under the package's namespace directory. They are projections of the two
 * authored files, never edited by hand, and a checker regenerates them and
 * compares bytes, so these functions are the one way they are spelled.
 */
import type { DraftDescriptor, InstallFile } from "./types.js";

/** The name a systems[] entry gives its system: `name`, or `role`, the alias kept for one revision. `name` wins where both are present. */
export const systemName = (s: unknown): string => {
  const e = s as { name?: unknown; role?: unknown } | null;
  return (typeof e?.name === "string" && e.name) || (typeof e?.role === "string" && e.role) || "";
};

/** NOT.md: where the agent stops, one refusal per line, and what always goes to a person. */
export function notMd(desc: DraftDescriptor): string {
  const body = ["# Where this agent stops", "", ...String(desc.refusals ?? "").split("\n").filter((l) => l.trim())];
  if (desc.escalates?.length) body.push("", "## What always goes to a person", "", ...desc.escalates.map((e) => `- ${e}`));
  return `${body.join("\n")}\n`;
}

/** RECORDS.md: the records the agent must leave, on every run. */
export function recordsMd(desc: DraftDescriptor): string {
  const body = ["# The records this agent must leave", "", "This is the contract. The agent leaves the following behind, on", "every run.", ""];
  for (const r of desc.records ?? []) {
    let line = `- ${r.name}`;
    if (r.when === "standing") line += " (kept across tasks)";
    // The em dash is part of the generated bytes that every implementation
    // must reproduce, so it stays.
    if (r.file) line += ` — at \`${r.file}\``;
    body.push(line);
  }
  body.push("", "An agent that leaves less than this does not do this job,", "whatever else it does well.");
  return `${body.join("\n")}\n`;
}

/** SYSTEMS.md: the systems the agent needs, by name, with their kind, access and what the access is for. */
export function systemsMd(desc: DraftDescriptor, inst: InstallFile): string {
  const kinds = new Map((inst.systems ?? []).map((s) => [systemName(s), s]));
  const body = [
    "# The systems this agent needs",
    "",
    "Named by what the work needs rather than by product. The access level",
    "is the most this work needs; a deployment that grants more is granting",
    "more than the job requires.",
    "",
    "| System | Kind | Access | What the access is for |",
    "|---|---|---|---|",
  ];
  for (const s of desc.systems ?? []) {
    const k = kinds.get(systemName(s)) ?? ({} as Partial<InstallFile["systems"][number]>);
    const extra: string[] = [];
    if (k.credential) extra.push(`credential \`${k.credential}\``);
    if (k.spends) extra.push(`spends per ${k.spends.unit}`);
    if (s.leaves) extra.push("the caller's material is sent to it");
    let needs = s.needs ?? "";
    if (extra.length) needs = `${needs ? `${needs}; ` : ""}${extra.join(", ")}`;
    body.push(`| ${systemName(s)} | ${k.kind ?? "directory"} | ${s.access} | ${needs} |`);
  }
  body.push("", "Whoever deploys this agent binds these systems to their own,", "and places any named credential. Nothing here names a product.");
  return `${body.join("\n")}\n`;
}

/** The three views, by their path in the package. */
export function generatedViews(desc: DraftDescriptor, inst: InstallFile, ns: string): Record<string, string> {
  return {
    [`${ns}/NOT.md`]: notMd(desc),
    [`${ns}/RECORDS.md`]: recordsMd(desc),
    [`${ns}/SYSTEMS.md`]: systemsMd(desc, inst),
  };
}
